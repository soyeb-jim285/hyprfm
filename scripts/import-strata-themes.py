#!/usr/bin/env python3
"""Port a Strata checkout's bundled catalog to HyprFM (Python 3.11+)."""

import argparse
import hashlib
import math
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]
COLOR_FIELDS = (
    "background", "surface", "text", "accent", "danger", "muted",
    "highlight", "border", "dim_text", "syntax_keyword", "syntax_string",
    "syntax_constant", "syntax_type", "syntax_preprocessor",
)


def channels(color):
    return tuple(int(color[index:index + 2], 16) for index in (1, 3, 5))


def blend(left, right, amount):
    # Match Strata's positive-channel f64::round, rather than Python's ties-to-even.
    return "#" + "".join(
        f"{math.floor(a + (b - a) * amount + 0.5):02x}"
        for a, b in zip(channels(left), channels(right))
    )


def luminance(color):
    def linear(channel):
        value = channel / 255
        return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4
    return sum(linear(channel) * weight
               for channel, weight in zip(channels(color), (0.2126, 0.7152, 0.0722)))


def contrast(left, right):
    low, high = sorted((luminance(left), luminance(right)))
    return (high + 0.05) / (low + 0.05)


def readable(color, background, foreground, ratio):
    # Strata lifts dim text in two passes, first on background, then on surface.
    for step in range(256):
        candidate = blend(color, foreground, step / 255)
        if contrast(candidate, background) >= ratio:
            return candidate
    raise ValueError(f"Foreground {foreground} cannot reach {ratio}:1 on {background}")


def render(theme, source_hash):
    dim = readable(theme["dim_text"], theme["background"], theme["text"], 4.5)
    dim = readable(dim, theme["surface"], theme["text"], 3.0)
    colors = {
        "base": theme["background"],
        "mantle": blend(theme["background"], theme["surface"], 0.5),
        "crust": theme["background"],
        "surface": theme["surface"],
        "overlay": theme["border"],
        "text": theme["text"],
        "subtext": blend(dim, theme["text"], 0.5),
        "muted": dim,
        "accent": theme["accent"],
        "success": theme["syntax_string"],
        "warning": theme["syntax_type"],
        "error": theme["danger"],
    }
    # The catalog has semantic/syntax colors, not a complete ANSI palette.
    # Use its red/green/yellow/blue/purple/cyan and foreground for both intensities.
    ansi = [theme[key] for key in (
        "background", "danger", "syntax_string", "syntax_type", "accent",
        "syntax_keyword", "syntax_preprocessor", "text", "border", "danger",
        "syntax_string", "syntax_type", "accent", "syntax_keyword",
        "syntax_preprocessor", "text",
    )]
    lines = [
        "# SPDX-License-Identifier: MIT",
        f"# Strata: {theme['name']} ({theme['id']})",
        f"# Source catalog SHA-256: {source_hash}",
        "# Generated by scripts/import-strata-themes.py; see themes/README.md.",
        "# License notices: licenses/Strata-MIT.txt and licenses/Tinted-Theming-MIT.txt.",
        "", "[colors]",
    ]
    lines += [f'{key} = "{value}"' for key, value in colors.items()]
    lines += ["", "[terminal]", "palette = ["]
    for start in (0, 8):
        lines.append("    " + ", ".join(f'"{value}"' for value in ansi[start:start + 8]) + ",")
    return "\n".join(lines + ["]", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("strata", type=Path, help="Path to a Strata source checkout")
    parser.add_argument("--check", action="store_true", help="Check the port without writing files")
    args = parser.parse_args()
    source = args.strata.expanduser() / "data/themes/catalog.toml"
    contents = source.read_bytes()
    catalog = tomllib.loads(contents.decode())["themes"]
    if not catalog:
        raise ValueError("The Strata catalog is empty")
    expected = {}
    for theme in catalog:
        theme_id = theme["id"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", theme_id):
            raise ValueError(f"Invalid theme ID: {theme_id!r}")
        if not theme["name"].strip() or "\n" in theme["name"]:
            raise ValueError(f"Invalid theme name: {theme_id}")
        for field in COLOR_FIELDS:
            if not re.fullmatch(r"#[0-9a-fA-F]{6}", theme[field]):
                raise ValueError(f"Invalid {field} in {theme_id}")
        path = ROOT / "themes" / f"strata-{theme_id}.toml"
        if path in expected:
            raise ValueError(f"Duplicate theme ID: {theme_id}")
        expected[path] = render(theme, hashlib.sha256(contents).hexdigest())
    stale = set((ROOT / "themes").glob("strata-*.toml")) - expected.keys()
    if stale:
        raise ValueError("Remove retired generated themes: " + ", ".join(sorted(p.name for p in stale)))
    if args.check:
        different = [p.name for p, text in expected.items() if not p.exists() or p.read_text() != text]
        if different:
            raise ValueError("Themes need importing: " + ", ".join(different))
        print(f"All {len(expected)} Strata themes match the source catalog.")
    else:
        for path, text in expected.items():
            path.write_text(text)
        print(f"Imported {len(expected)} Strata themes into {ROOT / 'themes'}.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, KeyError, ValueError) as error:
        raise SystemExit(str(error)) from error
